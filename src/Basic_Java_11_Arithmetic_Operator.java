public class Basic_Java_11_Arithmetic_Operator {
    public static void main(String[] args) {
        //Arithmetic Operator
        //  + , - , * , / , %
        int a = 10;
        int b = 5 ;

        System.out.println("Addition values is : "+ (a+b));
        System.out.println("Subtraction values is : "+ (a-b));
        System.out.println("Multiplication values is : "+ a*b);
        System.out.println("Division values is : "+ a/b);
        System.out.println("Modulus values is : "+ a % b);

    }
}
