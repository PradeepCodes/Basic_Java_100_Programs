public class Basic_Java_12_Relational_Operator {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        System.out.println("To check the Values of "+a+" and "+b+" are equal, the result is : "+ (a == b));

        System.out.println("To check the Values of "+a+" and "+b+" are not equal, the result is : "+ (a != b));

        System.out.println("To check the Values of "+a+" less than "+b+" the result is : "+ (a < b));
        System.out.println("To check the Values of "+a+" greater than "+b+" the result is : "+ (a > b));

        System.out.println("To check the Values of "+a+" less than or equals to "+b+" the result is : "+ (a <= b));
        System.out.println("To check the Values of "+a+" greater than or equals to "+b+" the result is : "+ (a >= b));

    }
}
